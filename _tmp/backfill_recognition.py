for ch, name, supp in TARGETS:
    f = Path(f"项目/现象学/notes/ch{ch}.json")
    d = json.loads(f.read_text(encoding="utf-8"))
    target = None
    for g in d["gestalten"]:
        for b in g["bewegung"]:
            if b[0] == name:
                target = b
                break
        if target:
            break
    if not target:
        # 模糊匹配
        for g in d["gestalten"]:
            for b in g["bewegung"]:
                if name.split("：")[0] in b[0]:
                    target = b
                    break
            if target:
                break
    if target:
        supps = target[4] if len(target) > 4 else []
        if not any(supp["title"][:8] in s.get("title", "") for s in supps):
            supps.append(supp)
            if len(target) > 4:
                target[4] = supps
            else:
                target.append(supps)
            f.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
            json.loads(f.read_text(encoding="utf-8"))
            print(f"ch{ch} [{target[0][:20]}] 已补")
        else:
            print(f"ch{ch} [{target[0][:20]}] 已存在")
    else:
        print(f"ch{ch} [{name}] 未找到环节")
