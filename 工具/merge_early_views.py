ALL = {"法哲学": B_法哲学, "现象学base": B_现象学base, "其余": B_其余}


def run(args, cwd):
    cmd = [sys.executable, str(ROOT / "add_viewpoint.py")] + args
    r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                       errors="replace", cwd=cwd)
    out = (r.stdout or "").strip()
    print(out)
    if r.returncode != 0:
        print("  !!ERR:", (r.stderr or "").strip()[-500:])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", choices=list(ALL.keys()) + ["all"], default="法哲学")
    args = ap.parse_args()
    batches = list(ALL.keys()) if args.batch == "all" else [args.batch]
    for b in batches:
        print(f"\n===== 批次：{b}（{len(ALL[b])} 条）=====")
        for c in ALL[b]:
            a = ["--type", c["type"]]
            if c["type"] == "lit":
                a += ["--lit", c["lit"], "--section", c["section"],
                      "--text", c["text"], "--anchor", c.get("anchor", "")]
                if c.get("refs"):
                    a += ["--refs", c["refs"]]
                if c.get("note"):
                    a += ["--note", c["note"]]
            elif c["type"] == "base":
                a += ["--text", c["text"], "--source", c["source"],
                      "--boundary", c.get("boundary", "")]
                if c.get("refs"):
                    a += ["--refs", c["refs"]]
            elif c["type"] == "phil":
                a += ["--phil", c["phil"], "--stage", c["stage"], "--work", c["work"],
                      "--text", c["text"], "--note", c.get("note", "")]
                if c.get("refs"):
                    a += ["--refs", c["refs"]]
            run(a, ROOT)


if __name__ == "__main__":
    main()
