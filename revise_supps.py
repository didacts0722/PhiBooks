def main():
    data = json.loads(P.read_text(encoding="utf-8"))
    n = 0
    for g in data["gestalten"]:
        for b in g["bewegung"]:
            if len(b) < 5 or not isinstance(b[4], list):
                continue
            new = []
            for s in b[4]:
                if s.get("title") in REVISED:
                    new.append(REVISED[s["title"]])
                    n += 1
                else:
                    new.append(s)
            b[4] = new
    P.write_text(json.dumps(data, ensure_ascii=False, indent=1),
                 encoding="utf-8", newline="\n")
    print(f"ch4.json 已修订 {n} 条补充（去译文引文/去哲学家批评）")


if __name__ == "__main__":
    main()
