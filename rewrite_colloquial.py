def main():
    by_file = {}
    for fname, title, content in REWRITES:
        by_file.setdefault(fname, []).append((title, content))
    for fname, items in by_file.items():
        p = ROOT / "notes_pheno" / fname
        data = json.loads(p.read_text(encoding="utf-8"))
        n = 0
        for title, content in items:
            hit = False
            for g in data["gestalten"]:
                for b in g["bewegung"]:
                    if len(b) > 4 and isinstance(b[4], list):
                        for s in b[4]:
                            if s.get("title") == title:
                                s["content"] = content
                                hit = True
                                n += 1
            if not hit:
                raise SystemExit(f"未找到补充：{fname} / {title}")
        p.write_text(json.dumps(data, ensure_ascii=False, indent=1),
                     encoding="utf-8", newline="\n")
        print(f"{fname} 改写 {n} 条")
    print("完成。")


if __name__ == "__main__":
    main()
