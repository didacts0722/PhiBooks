BATCH = {"ch5": CH5, "ch6": CH6, "ch7": CH7}


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else "ch5"
    items = BATCH[which]
    p = ROOT / "项目/现象学/notes" / f"{which}.json"
    data = json.loads(p.read_text(encoding="utf-8"))
    done = 0
    for title, supp in items:
        found = False
        for g in data["gestalten"]:
            for b in g["bewegung"]:
                if b[0] == title:
                    if len(b) < 5 or b[4] is None:
                        while len(b) < 5:
                            b.append(None)
                        b[4] = []
                    # 去重（同 title 重插时）
                    b[4] = [s for s in b[4] if s.get("title") != supp["title"]]
                    b[4].append(supp)
                    found = True
                    break
            if found:
                break
        if not found:
            raise SystemExit(f"未找到环节：{which} / {title}")
        done += 1
    p.write_text(json.dumps(data, ensure_ascii=False, indent=1),
                 encoding="utf-8", newline="\n")
    print(f"{which}.json 已插入 {done} 条补充")


if __name__ == "__main__":
    main()
