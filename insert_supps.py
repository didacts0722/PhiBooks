def main():
    by_file = {}
    for fname, title, supp in SUPPS:
        by_file.setdefault(fname, []).append((title, supp))
    for fname, items in by_file.items():
        p = ROOT / "项目/现象学/notes" / fname
        data = json.loads(p.read_text(encoding="utf-8"))
        for title, supp in items:
            found = False
            for g in data["gestalten"]:
                for b in g["bewegung"]:
                    if b[0] == title:
                        if len(b) < 5 or b[4] is None:
                            while len(b) < 5:
                                b.append(None)
                            b[4] = [supp]
                        else:
                            b[4].append(supp)
                        found = True
                        break
                if found:
                    break
            if not found:
                raise SystemExit(f"未找到环节：{fname} / {title}")
        p.write_text(json.dumps(data, ensure_ascii=False, indent=1),
                     encoding="utf-8", newline="\n")
        print(f"已更新 {fname}：{len(items)} 条补充")
    print("完成。")


if __name__ == "__main__":
    main()
